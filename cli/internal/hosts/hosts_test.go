const fixtureHosts = "127.0.0.1 localhost\n# unrelated comment\n192.0.2.10 retained.test\n"

func TestSyncCreatesBlockAndIsIdempotent(t *testing.T) {
	c, apps, _ := discoverFixture(t)
	d, err := Discover(c, apps)
	if err != nil {
		t.Fatal(err)
	}
	block := Block(d, DefaultAddress)
	got, err := ReplaceBlock(fixtureHosts, block)
	if err != nil {
		t.Fatal(err)
	}
	want := fixtureHosts + `
# BEGIN DEVARCH HOSTS
# Generated by devarch hosts sync; rerun to refresh.
# Infrastructure services
127.0.0.1 adminer.test nginx-proxy-manager.test npm.test redis.test
# Development applications
127.0.0.1 alpha.test beta.test
# Development tools
127.0.0.1 devarch.test
# END DEVARCH HOSTS
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	again, err := ReplaceBlock(got, block)
	if err != nil || again != got {
		t.Fatalf("re-sync changed a current file: %v\n%s", err, again)
	}
	if d.Count() != 7 {
		t.Fatalf("count = %d", d.Count())
	}
}

func TestSyncRefreshesBlockAndKeepsOutsideContent(t *testing.T) {
	old := fixtureHosts + "\n" + BeginMarker + "\n127.0.0.1 stale.test\n" + EndMarker + "\n# after\n"
	got, err := ReplaceBlock(old, Block(Domains{Services: []string{"fresh"}}, DefaultAddress))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(got, "stale.test") || !strings.Contains(got, "127.0.0.1 fresh.test\n") ||
		!strings.HasPrefix(got, fixtureHosts) || !strings.HasSuffix(got, EndMarker+"\n# after\n") {
		t.Fatalf("got:\n%s", got)
	}
}

