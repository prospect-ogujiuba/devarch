func TestManagerUnixWritesInPlace(t *testing.T) {
	file := filepath.Join(t.TempDir(), "hosts")
	os.WriteFile(file, []byte(fixtureHosts), 0o644)
	f := &runner.Fake{}
	m := &Manager{Platform: Unix, File: file, Runner: f}
	res, err := m.Sync(context.Background(), Block(Domains{Services: []string{"x"}}, DefaultAddress))
	if err != nil || !res.Changed {
		t.Fatalf("%+v %v", res, err)
	}
	if res, _ = m.Sync(context.Background(), Block(Domains{Services: []string{"x"}}, DefaultAddress)); res.Changed {
		t.Fatal("second sync reported a change")
	}
	if _, err := m.Add(context.Background(), "demo.test", DefaultAddress); err != nil {
		t.Fatal(err)
	}
	if _, err := m.Remove(context.Background(), "demo.test"); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(file)
	if strings.Contains(string(data), "demo.test") || !strings.Contains(string(data), "x.test") || len(f.Cmds) != 0 {
		t.Fatalf("file:\n%s\ncmds: %v", data, f.Lines())
	}
}

// The embedded PowerShell helpers keep their own encoding and line-ending
// behaviour; exercise them against a fixture when PowerShell is reachable.
func TestWindowsHelpersAgainstFixture(t *testing.T) {
	ps, err := findPowerShell()
	if err != nil {
		t.Skip("powershell.exe not available")
	}
	if _, err := exec.LookPath("wslpath"); err != nil {
		t.Skip("wslpath not available")
	}
	dir := t.TempDir()
	m := &Manager{ScriptDir: dir}
	run := func(script string, args ...string) {
		t.Helper()
		path, err := m.installScript(script)
		if err != nil {
			t.Fatal(err)
		}
		argv := append([]string{ps, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", path}, args...)
		// Under WSL, go through the interop host as Manager.powershell does.
		name := "/init"
		if _, err := os.Stat("/init"); err != nil || !IsWSL() {
			name, argv = argv[0], argv[1:]
		}
		if out, err := exec.Command(name, argv...).CombinedOutput(); err != nil {
			t.Fatalf("%s: %v\n%s", script, err, out)
		}
	}
	winPath := func(p string) string {
		out, err := exec.Command("wslpath", "-w", p).Output()
		if err != nil {
			t.Fatal(err)
		}
		return strings.TrimSpace(string(out))
	}

	fixture := filepath.Join(dir, "windows-hosts")
	original := "# comment\r\n127.0.0.1    first.test    second.test\r\n"
	os.WriteFile(fixture, []byte(original), 0o644)
	run("register-host.ps1", "-HostName", "moneytrees.test", "-HostsPath", winPath(fixture))
	data, _ := os.ReadFile(fixture)
	if string(data) != original+"127.0.0.1\tmoneytrees.test\r\n" {
		t.Fatalf("register reformatted the file: %q", data)
	}

	block := Block(Domains{Services: []string{"redis"}}, DefaultAddress)
	run("sync-hosts.ps1", "-BlockBase64", base64.StdEncoding.EncodeToString([]byte(block)), "-HostsPath", winPath(fixture))
	data, _ = os.ReadFile(fixture)
	if !strings.Contains(string(data), "\r\n# BEGIN DEVARCH HOSTS\r\n") || !strings.Contains(string(data), "127.0.0.1 redis.test\r\n") {
		t.Fatalf("sync output: %q", data)
	}
}
